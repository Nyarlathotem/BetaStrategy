-- Q16（limit=10）：3 只 ETF 复权净值与中证 500 在约三个月窗口的收益对齐。
WITH etf AS (
  SELECT F_INFO_WINDCODE, PRICE_DATE, F_NAV_ADJUSTED,
         LAG(F_NAV_ADJUSTED) OVER (
           PARTITION BY F_INFO_WINDCODE ORDER BY PRICE_DATE
         ) AS PREV_NAV
  FROM WDZX.CHINAMUTUALFUNDNAV
  WHERE F_INFO_WINDCODE IN ('510500.SH','510510.SH','512500.SH')
    AND PRICE_DATE BETWEEN '20260220' AND '20260531'
),
idx AS (
  SELECT TRADE_DT, S_DQ_CLOSE,
         LAG(S_DQ_CLOSE) OVER (ORDER BY TRADE_DT) AS PREV_CLOSE
  FROM WDZX.AINDEXEODPRICES
  WHERE S_INFO_WINDCODE = '000905.SH'
    AND TRADE_DT BETWEEN '20260220' AND '20260531'
)
SELECT e.F_INFO_WINDCODE,
       COUNT(*) AS ALIGNED_DAYS,
       COUNT(CASE WHEN e.PREV_NAV IS NOT NULL AND i.PREV_CLOSE IS NOT NULL THEN 1 END) AS RETURN_PAIRS,
       MIN(e.PRICE_DATE) AS FIRST_ALIGNED_DT,
       MAX(e.PRICE_DATE) AS LAST_ALIGNED_DT
FROM etf e
JOIN idx i ON i.TRADE_DT = e.PRICE_DATE
WHERE e.PRICE_DATE BETWEEN '20260301' AND '20260531'
GROUP BY e.F_INFO_WINDCODE;

