-- Q01（limit=5）：当前已上市有效 ETF 候选及审计日开/收盘集合竞价可成交数量。
WITH etf AS (
  SELECT DISTINCT c.S_INFO_WINDCODE
  FROM WDZX.CHINAETFINVESTCLASS c
  JOIN WDZX.CHINAMUTUALFUNDDESCRIPTION d
    ON d.F_INFO_WINDCODE = c.S_INFO_WINDCODE
  WHERE d.LISTEDFUNDORNOT = 1
    AND d.F_INFO_STATUS = 101001000
    AND d.F_INFO_LISTDATE <= '20260916'
    AND (d.F_INFO_DELISTDATE IS NULL OR d.F_INFO_DELISTDATE > '20260916')
    AND (c.S_INFO_WINDCODE LIKE '%.SH' OR c.S_INFO_WINDCODE LIKE '%.SZ')
)
SELECT COUNT(*) AS IDENTIFIED_LIVE_ETFS,
       COUNT(a.S_INFO_WINDCODE) AS WITH_AUCTION_ROW,
       COUNT(CASE WHEN a.OPEN_AUCTION_PRICE > 0 AND a.OPEN_AUCTION_VOLUME > 0 THEN 1 END) AS WITH_VALID_OPEN_AUCTION,
       COUNT(CASE WHEN a.CLOSE_AUCTION_PRICE > 0 AND a.CLOSE_AUCTION_VOLUME > 0 THEN 1 END) AS WITH_VALID_CLOSE_AUCTION
FROM etf e
LEFT JOIN WDZX.CHINACLOSEDFUNDAUCTION a
  ON a.S_INFO_WINDCODE = e.S_INFO_WINDCODE
 AND a.TRADE_DT = '20260916';

