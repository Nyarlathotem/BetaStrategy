-- Q40（limit=10）：按调仓日前已公告净资产取规模前 50% 后的集合竞价覆盖。
WITH asof_dates AS (
  SELECT '20190801' AS ASOF_DT FROM DUAL UNION ALL
  SELECT '20210601' FROM DUAL UNION ALL
  SELECT '20230601' FROM DUAL UNION ALL
  SELECT '20250603' FROM DUAL UNION ALL
  SELECT '20260601' FROM DUAL
), etf_pool AS (
  SELECT DISTINCT x.ASOF_DT, s.F_INFO_WINDCODE AS CODE
  FROM asof_dates x
  JOIN WDZX.CHINAMUTUALFUNDSECTOR s
    ON s.S_INFO_SECTOR = '2001020200'
   AND s.S_INFO_SECTORENTRYDT <= x.ASOF_DT
   AND (s.S_INFO_SECTOREXITDT IS NULL OR s.S_INFO_SECTOREXITDT > x.ASOF_DT)
  JOIN WDZX.CHINAMUTUALFUNDDESCRIPTION d
    ON d.F_INFO_WINDCODE = s.F_INFO_WINDCODE
   AND d.LISTEDFUNDORNOT = 1
   AND d.F_INFO_LISTDATE <= x.ASOF_DT
   AND (d.F_INFO_DELISTDATE IS NULL OR d.F_INFO_DELISTDATE > x.ASOF_DT)
  WHERE s.F_INFO_WINDCODE LIKE '%.SH' OR s.F_INFO_WINDCODE LIKE '%.SZ'
), asset_candidates AS (
  SELECT e.ASOF_DT, e.CODE, p.F_PRT_NETASSET,
         ROW_NUMBER() OVER (
           PARTITION BY e.ASOF_DT, e.CODE
           ORDER BY p.F_PRT_ENDDATE DESC, p.F_ANN_DATE DESC, p.OPDATE DESC
         ) AS RN
  FROM etf_pool e
  JOIN WDZX.CHINAMUTUALFUNDASSETPORTFOLIO p
    ON p.S_INFO_WINDCODE = e.CODE
   AND p.F_ANN_DATE < e.ASOF_DT
   AND p.F_PRT_NETASSET > 0
), latest_asset AS (
  SELECT ASOF_DT, CODE, F_PRT_NETASSET
  FROM asset_candidates
  WHERE RN = 1
), ranked_asset AS (
  SELECT ASOF_DT, CODE, F_PRT_NETASSET,
         ROW_NUMBER() OVER (
           PARTITION BY ASOF_DT ORDER BY F_PRT_NETASSET DESC, CODE
         ) AS ASSET_RANK,
         COUNT(*) OVER (PARTITION BY ASOF_DT) AS ASSET_COUNT
  FROM latest_asset
), high_scale AS (
  SELECT ASOF_DT, CODE
  FROM ranked_asset
  WHERE ASSET_RANK <= CEIL(ASSET_COUNT * 0.5)
), pool_counts AS (
  SELECT ASOF_DT, COUNT(*) AS ETF_COUNT
  FROM etf_pool
  GROUP BY ASOF_DT
), asset_counts AS (
  SELECT ASOF_DT, COUNT(*) AS WITH_PIT_ASSET
  FROM latest_asset
  GROUP BY ASOF_DT
)
SELECT h.ASOF_DT, p.ETF_COUNT, c.WITH_PIT_ASSET,
       COUNT(*) AS HIGH_SCALE_COUNT,
       COUNT(a.S_INFO_WINDCODE) AS WITH_AUCTION_ROW,
       COUNT(CASE WHEN a.OPEN_AUCTION_PRICE > 0 AND a.OPEN_AUCTION_VOLUME > 0 THEN 1 END) AS VALID_OPEN_COUNT,
       COUNT(CASE WHEN a.CLOSE_AUCTION_PRICE > 0 AND a.CLOSE_AUCTION_VOLUME > 0 THEN 1 END) AS VALID_CLOSE_COUNT,
       COUNT(CASE WHEN a.OPEN_AUCTION_PRICE > 0 AND a.OPEN_AUCTION_VOLUME > 0
                       AND a.CLOSE_AUCTION_PRICE > 0 AND a.CLOSE_AUCTION_VOLUME > 0
                  THEN 1 END) AS VALID_BOTH_COUNT,
       ROUND(100 * COUNT(CASE WHEN a.OPEN_AUCTION_PRICE > 0 AND a.OPEN_AUCTION_VOLUME > 0
                                  AND a.CLOSE_AUCTION_PRICE > 0 AND a.CLOSE_AUCTION_VOLUME > 0
                             THEN 1 END) / COUNT(*), 2) AS VALID_BOTH_PCT
FROM high_scale h
JOIN pool_counts p ON p.ASOF_DT = h.ASOF_DT
JOIN asset_counts c ON c.ASOF_DT = h.ASOF_DT
LEFT JOIN WDZX.CHINACLOSEDFUNDAUCTION a
  ON a.S_INFO_WINDCODE = h.CODE
 AND a.TRADE_DT = h.ASOF_DT
GROUP BY h.ASOF_DT, p.ETF_COUNT, c.WITH_PIT_ASSET
ORDER BY h.ASOF_DT;

