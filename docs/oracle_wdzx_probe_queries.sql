-- Q18（limit=10）：约 16 个月的沪深 300 月末数据计算 MA3、MA12、S3、S12。
WITH ranked AS (
  SELECT TRADE_DT, S_DQ_CLOSE, SUBSTR(TRADE_DT,1,6) AS YM,
         ROW_NUMBER() OVER (
           PARTITION BY SUBSTR(TRADE_DT,1,6) ORDER BY TRADE_DT DESC
         ) AS RN
  FROM WDZX.AINDEXEODPRICES
  WHERE S_INFO_WINDCODE = '000300.SH'
    AND TRADE_DT BETWEEN '20250501' AND '20260831'
),
monthly AS (
  SELECT TRADE_DT, YM, S_DQ_CLOSE
  FROM ranked
  WHERE RN = 1
),
ma AS (
  SELECT TRADE_DT, YM, S_DQ_CLOSE,
         AVG(S_DQ_CLOSE) OVER (ORDER BY YM ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) AS MA3,
         AVG(S_DQ_CLOSE) OVER (ORDER BY YM ROWS BETWEEN 11 PRECEDING AND CURRENT ROW) AS MA12,
         COUNT(*) OVER (ORDER BY YM ROWS BETWEEN 11 PRECEDING AND CURRENT ROW) AS MA12_OBS
  FROM monthly
),
slopes AS (
  SELECT TRADE_DT, YM, S_DQ_CLOSE, MA3, MA12, MA12_OBS,
         MA3 / LAG(MA3) OVER (ORDER BY YM) - 1 AS S3,
         MA12 / LAG(MA12) OVER (ORDER BY YM) - 1 AS S12
  FROM ma
)
SELECT TRADE_DT, YM, S_DQ_CLOSE, MA3, MA12, MA12_OBS, S3, S12
FROM slopes
WHERE YM IN ('202607','202608')
ORDER BY YM;

