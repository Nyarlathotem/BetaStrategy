-- Q28（limit=50）：按表聚合代码、日期、OHLC、复权、量额、交易状态和净值字段能力。
WITH col_caps AS (
  SELECT c.OWNER, c.TABLE_NAME, c.COLUMN_NAME,
         NVL(cc.COMMENTS, '') AS COLUMN_COMMENT,
         CASE WHEN c.COLUMN_NAME IN
              ('S_INFO_WINDCODE','F_INFO_WINDCODE','SEC_ID','WINDCODE','S_INFO_CODE')
              THEN 1 ELSE 0 END AS HAS_CODE,
         CASE WHEN c.COLUMN_NAME IN
              ('TRADE_DT','PRICE_DATE','TRADE_DATE','S_DQ_DATE','TRADE_DAYS')
              THEN 1 ELSE 0 END AS HAS_TRADE_DATE,
         CASE WHEN c.COLUMN_NAME IN
              ('S_DQ_OPEN','OPEN_PRICE','OPEN_AUCTION_PRICE','F_DQ_OPEN')
              OR INSTR(NVL(cc.COMMENTS, ''), '开盘价') > 0
              THEN 1 ELSE 0 END AS HAS_OPEN,
         CASE WHEN c.COLUMN_NAME IN
              ('S_DQ_CLOSE','CLOSE_PRICE','CLOSE_AUCTION_PRICE','F_DQ_CLOSE')
              OR INSTR(NVL(cc.COMMENTS, ''), '收盘价') > 0
              THEN 1 ELSE 0 END AS HAS_CLOSE,
         CASE WHEN c.COLUMN_NAME IN ('S_DQ_PRECLOSE','PRECLOSE','PRE_CLOSE')
              OR INSTR(NVL(cc.COMMENTS, ''), '前收盘') > 0
              THEN 1 ELSE 0 END AS HAS_PRECLOSE,
         CASE WHEN REGEXP_LIKE(c.COLUMN_NAME, 'ADJ(OPEN|CLOSE|FACTOR)|ADJUSTED')
              OR INSTR(NVL(cc.COMMENTS, ''), '复权') > 0
              THEN 1 ELSE 0 END AS HAS_ADJUST,
         CASE WHEN REGEXP_LIKE(c.COLUMN_NAME, '(^|_)(VOLUME|VOL)($|_)')
              OR INSTR(NVL(cc.COMMENTS, ''), '成交量') > 0
              THEN 1 ELSE 0 END AS HAS_VOLUME,
         CASE WHEN REGEXP_LIKE(c.COLUMN_NAME, '(^|_)(AMOUNT|AMT)($|_)')
              OR INSTR(NVL(cc.COMMENTS, ''), '成交额') > 0
              THEN 1 ELSE 0 END AS HAS_AMOUNT,
         CASE WHEN REGEXP_LIKE(c.COLUMN_NAME, 'TRADESTATUS|SUSPEND|STOPPING|MAXUP|MAXDOWN|LIMIT')
              OR REGEXP_LIKE(NVL(cc.COMMENTS, ''), '停牌|交易状态|涨停|跌停')
              THEN 1 ELSE 0 END AS HAS_TRADE_STATE,
         CASE WHEN REGEXP_LIKE(c.COLUMN_NAME, 'NAV|IOPV')
              OR REGEXP_LIKE(NVL(cc.COMMENTS, ''), '净值|IOPV')
              THEN 1 ELSE 0 END AS HAS_NAV
  FROM ALL_TAB_COLUMNS c
  LEFT JOIN ALL_COL_COMMENTS cc
    ON cc.OWNER = c.OWNER
   AND cc.TABLE_NAME = c.TABLE_NAME
   AND cc.COLUMN_NAME = c.COLUMN_NAME
  WHERE c.OWNER = 'WDZX'
), table_caps AS (
  SELECT OWNER, TABLE_NAME,
         MAX(HAS_CODE) AS HAS_CODE,
         MAX(HAS_TRADE_DATE) AS HAS_TRADE_DATE,
         MAX(HAS_OPEN) AS HAS_OPEN,
         MAX(HAS_CLOSE) AS HAS_CLOSE,
         MAX(HAS_PRECLOSE) AS HAS_PRECLOSE,
         MAX(HAS_ADJUST) AS HAS_ADJUST,
         MAX(HAS_VOLUME) AS HAS_VOLUME,
         MAX(HAS_AMOUNT) AS HAS_AMOUNT,
         MAX(HAS_TRADE_STATE) AS HAS_TRADE_STATE,
         MAX(HAS_NAV) AS HAS_NAV
  FROM col_caps
  GROUP BY OWNER, TABLE_NAME
)
SELECT t.TABLE_NAME, o.OBJECT_TYPE, tc.COMMENTS AS TABLE_COMMENT,
       t.HAS_CODE, t.HAS_TRADE_DATE, t.HAS_OPEN, t.HAS_CLOSE,
       t.HAS_PRECLOSE, t.HAS_ADJUST, t.HAS_VOLUME, t.HAS_AMOUNT,
       t.HAS_TRADE_STATE, t.HAS_NAV,
       (t.HAS_CODE + t.HAS_TRADE_DATE + t.HAS_OPEN + t.HAS_CLOSE +
        t.HAS_PRECLOSE + t.HAS_ADJUST + t.HAS_VOLUME + t.HAS_AMOUNT +
        t.HAS_TRADE_STATE) AS MARKET_CAPABILITY_SCORE
FROM table_caps t
JOIN ALL_OBJECTS o
  ON o.OWNER = t.OWNER
 AND o.OBJECT_NAME = t.TABLE_NAME
LEFT JOIN ALL_TAB_COMMENTS tc
  ON tc.OWNER = t.OWNER
 AND tc.TABLE_NAME = t.TABLE_NAME
WHERE t.HAS_CODE = 1
  AND (t.HAS_TRADE_DATE + t.HAS_OPEN + t.HAS_CLOSE + t.HAS_PRECLOSE +
       t.HAS_ADJUST + t.HAS_VOLUME + t.HAS_AMOUNT + t.HAS_TRADE_STATE +
